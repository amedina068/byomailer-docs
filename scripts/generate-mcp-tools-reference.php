<?php

/*
 * Generates mcp/tools-reference.md from the MCP tool classes of the app.
 *
 * Usage:
 *   BYOMAILER_APP_PATH=/path/to/byomailer php scripts/generate-mcp-tools-reference.php > mcp/tools-reference.md
 *   php scripts/generate-mcp-tools-reference.php /path/to/byomailer > mcp/tools-reference.md
 *
 * The app must have its Composer dependencies. The script sets
 * APP_URL=https://byomailer.example before the app starts, because some tool
 * descriptions can contain the URL of the instance. A variable of the process
 * wins over the .env file of the app.
 */

$appPath = $argv[1] ?? (getenv('BYOMAILER_APP_PATH') ?: null);

foreach (['APP_URL' => 'https://byomailer.example'] as $name => $value) {
    putenv("{$name}={$value}");
    $_ENV[$name] = $value;
    $_SERVER[$name] = $value;
}

if (! $appPath || ! is_file(rtrim($appPath, '/').'/vendor/autoload.php')) {
    fwrite(STDERR, "Set BYOMAILER_APP_PATH, or give the app path as the first argument.\n");
    fwrite(STDERR, "The app must have vendor/autoload.php. Run composer install in the app first.\n");
    exit(1);
}

$appPath = rtrim($appPath, '/');

require $appPath.'/vendor/autoload.php';
$app = require $appPath.'/bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();

$serverClass = 'App\\Mcp\\Servers\\ByoMailerServer';
$toolClasses = (new ReflectionClass($serverClass))->getProperty('tools')->getDefaultValue();

$tools = [];
foreach ($toolClasses as $class) {
    $tools[] = $app->make($class)->toArray();
}

/** Escape a value for a Markdown table cell. */
function cell(?string $value): string
{
    $value = str_replace(["\r\n", "\n", "\r"], ' ', (string) $value);

    return trim(str_replace('|', '\\|', $value));
}

/** A short type label for one JSON schema property. */
function typeLabel(array $schema): string
{
    $type = $schema['type'] ?? 'any';
    $type = is_array($type) ? implode(' or ', $type) : $type;

    if ($type === 'array' && isset($schema['items']['type'])) {
        $itemType = $schema['items']['type'];

        return 'array of '.(is_array($itemType) ? implode(' or ', $itemType) : $itemType);
    }

    return $type;
}

/** The rows of the arguments table. Nested object fields are flattened. */
function argumentRows(array $schema, string $prefix = ''): array
{
    $rows = [];
    $required = $schema['required'] ?? [];

    foreach ((array) ($schema['properties'] ?? []) as $name => $property) {
        $property = (array) $property;
        $fullName = $prefix.$name;
        $enum = '';
        if (isset($property['enum'])) {
            $enum = implode(', ', array_map(
                fn ($value) => '`'.(is_string($value) ? $value : json_encode($value)).'`',
                $property['enum']
            ));
        }

        $rows[] = [
            '`'.$fullName.'`',
            typeLabel($property),
            in_array($name, $required, true) ? 'Yes' : 'No',
            $enum,
            cell($property['description'] ?? ''),
        ];

        if (($property['type'] ?? null) === 'object' && isset($property['properties'])) {
            $rows = array_merge($rows, argumentRows($property, $fullName.'.'));
        }

        if (($property['type'] ?? null) === 'array'
            && ($property['items']['type'] ?? null) === 'object'
            && isset($property['items']['properties'])) {
            $rows = array_merge($rows, argumentRows($property['items'], $fullName.'[].'));
        }
    }

    return $rows;
}

/** "Yes", "No", or "-" when the tool does not set the annotation. */
function hint(array $tool, string $name): string
{
    // laravel/mcp returns an empty object, not an array, when a tool has no annotations.
    $annotations = (array) ($tool['annotations'] ?? []);
    if (! array_key_exists($name, $annotations)) {
        return '-';
    }

    return $annotations[$name] ? 'Yes' : 'No';
}

$out = [];
$out[] = '---';
$out[] = 'title: MCP tools reference';
$out[] = 'description: The name, the description and the arguments of each tool of the BYOMailer MCP server.';
$out[] = 'order: 3';
$out[] = '---';
$out[] = '';
$out[] = '<!-- Generated by scripts/generate-mcp-tools-reference.php. Do not edit by hand. -->';
$out[] = '';
$out[] = '# MCP tools reference';
$out[] = '';
$out[] = 'The BYOMailer MCP server has '.count($tools).' tools. This page lists them in the order that `tools/list` returns them.';
$out[] = '';
$out[] = 'A script makes this page from the tool classes in `app/Mcp/Tools`. Each description is the text that the server sends to the agent.';
$out[] = '';
$out[] = 'The hint columns show the MCP tool annotations. A client can use them to ask a person before a call. A dash means that the tool does not set the hint.';
$out[] = '';
$out[] = 'Read [the MCP overview](overview.md) for the workflow and the error format.';
$out[] = '';
$out[] = '## Summary';
$out[] = '';
$out[] = '| Tool | Title | Read only | Destructive |';
$out[] = '| --- | --- | --- | --- |';

foreach ($tools as $tool) {
    $out[] = '| [`'.$tool['name'].'`](#'.$tool['name'].') | '.cell($tool['title'] ?? '').' | '.hint($tool, 'readOnlyHint').' | '.hint($tool, 'destructiveHint').' |';
}

foreach ($tools as $tool) {
    $out[] = '';
    $out[] = '## '.$tool['name'];
    $out[] = '';
    if (! empty($tool['title'])) {
        $out[] = '**'.$tool['title'].'**';
        $out[] = '';
    }
    $out[] = '> '.str_replace("\n", "\n> ", trim((string) ($tool['description'] ?? '')));
    $out[] = '';

    $rows = argumentRows($tool['inputSchema'] ?? []);
    if ($rows === []) {
        $out[] = 'This tool takes no arguments.';

        continue;
    }

    $out[] = '| Argument | Type | Required | Values | Description |';
    $out[] = '| --- | --- | --- | --- | --- |';
    foreach ($rows as $row) {
        $out[] = '| '.implode(' | ', $row).' |';
    }
}

echo implode("\n", $out)."\n";
